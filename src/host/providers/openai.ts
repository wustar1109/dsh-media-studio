/**
 * OpenAI Images / Videos adapter. Also serves `openai-compat` gateways: the
 * request shapes below are the de-facto relay contract (JSON generate, multipart
 * edit, async video with a `/content` download).
 */
import type { GeneratedImage, GeneratedVideo, ImageRequest, VideoRequest } from '../types.js'
import { bearer, clampSeconds, decodeImages, failure, pollUntil, pixelsOf, videoResult } from './common.js'
import { errorBody, fetchWithTimeout, getWithRetry, joinUrl, postJson, readBounded } from '../util.js'

const ERROR_LIMIT_NOTE = 'check the model id, size and whether the gateway supports this endpoint'

/**
 * The Videos API only accepts a small set of pixel sizes (not arbitrary aspect
 * ratios), so portrait/landscape map onto its documented pairs rather than the
 * image size table.
 */
function soraSize(aspectRatio: string, resolution: string): string {
  const hd = resolution.toUpperCase() === '1080P'
  if (aspectRatio === '9:16') return hd ? '1080x1920' : '720x1280'
  return hd ? '1920x1080' : '1280x720'
}

export async function generateOpenAIImage(request: ImageRequest): Promise<GeneratedImage[]> {
  const base = (request.channel.baseUrl ?? 'https://api.openai.com/v1').replace(/\/+$/, '')
  const model = (request.channel.imageModel ?? '').trim()
  if (model === '') throw new Error('OpenAI 通道没有配置 imageModel')
  const size = pixelsOf(request.size, request.aspectRatio)
  const headers = bearer(request.apiKey, request.channel.headers)
  let response: Response
  if (request.refs.length > 0) {
    const form = new FormData()
    const field = request.refs.length > 1 ? 'image[]' : 'image'
    request.refs.forEach((ref, index) => {
      form.append(field, new Blob([new Uint8Array(ref.data)], { type: ref.mime }), `reference-${String(index + 1)}.png`)
    })
    form.append('prompt', request.prompt)
    form.append('model', model)
    form.append('n', String(request.n))
    form.append('size', size)
    if (request.quality !== undefined && request.quality !== '') form.append('quality', request.quality)
    if (!model.startsWith('gpt-image')) form.append('response_format', 'b64_json')
    for (const [key, value] of Object.entries(request.channel.extraBody ?? {})) form.append(key, String(value))
    response = await fetchWithTimeout(joinUrl(base, 'images/edits'), {
      method: 'POST',
      headers, // boundary must be generated by fetch itself
      body: form,
      signal: request.signal,
    }, 300_000)
  } else {
    response = await postJson(joinUrl(base, 'images/generations'), {
      model,
      prompt: request.prompt,
      n: request.n,
      size,
      ...(request.quality === undefined || request.quality === '' ? {} : { quality: request.quality }),
      ...(model.startsWith('gpt-image') ? {} : { response_format: 'b64_json' }),
      ...request.channel.extraBody,
    }, headers, 300_000, request.signal)
  }
  if (!response.ok) throw await failure(response, 'OpenAI 图像生成', request.apiKey)
  const payload = await response.json()
  const images = await decodeImages(payload, request.maxBytes, request.signal, request.apiKey)
  if (images.length > request.n) images.length = request.n
  return images
}

/** Upload one reference for the video API; it wants multipart on submit. */
export async function generateOpenAIVideo(request: VideoRequest): Promise<GeneratedVideo> {
  const base = (request.channel.baseUrl ?? 'https://api.openai.com/v1').replace(/\/+$/, '')
  const model = (request.channel.videoModel ?? '').trim()
  if (model === '') throw new Error('OpenAI 通道没有配置 videoModel')
  const headers = bearer(request.apiKey, request.channel.headers)
  const size = soraSize(request.aspectRatio, request.resolution)
  const submit = (): Promise<Response> => {
    if (request.refs.length === 0) {
      return postJson(joinUrl(base, 'videos'), {
        model,
        prompt: request.prompt,
        seconds: String(clampSeconds(request.seconds, 4, 12)),
        size,
        ...request.channel.extraBody,
      }, headers, 120_000, request.signal)
    }
    const form = new FormData()
    form.append('model', model)
    form.append('prompt', request.prompt)
    form.append('seconds', String(clampSeconds(request.seconds, 4, 12)))
    form.append('size', size)
    form.append('input_reference', new Blob([new Uint8Array(request.refs[0]!.data)], { type: request.refs[0]!.mime }), 'reference.png')
    for (const [key, value] of Object.entries(request.channel.extraBody ?? {})) form.append(key, String(value))
    return fetchWithTimeout(joinUrl(base, 'videos'), { method: 'POST', headers, body: form, signal: request.signal }, 120_000)
  }
  const response = await submit()
  if (!response.ok) throw await failure(response, 'OpenAI 视频提交', request.apiKey)
  const created = await response.json() as { id?: unknown; status?: unknown }
  const id = typeof created.id === 'string' ? created.id : ''
  if (id === '') throw new Error(`OpenAI 视频提交没有返回 id（${ERROR_LIMIT_NOTE}）`)
  request.onProgress?.('视频任务已提交，等待渲染')

  return pollUntil<GeneratedVideo>(async () => {
    const poll = await getWithRetry(joinUrl(base, `videos/${encodeURIComponent(id)}`), headers, 60_000, request.signal)
    if (!poll.ok) {
      if (poll.status === 404) throw new Error('OpenAI 视频任务不存在（可能已过期）')
      throw new Error(`OpenAI 视频查询失败：HTTP ${String(poll.status)} ${await errorBody(poll, request.apiKey)}`)
    }
    const body = await poll.json() as { status?: unknown; error?: unknown; progress?: unknown; seconds?: unknown }
    const status = String(body.status ?? '').toLowerCase()
    if (status === 'failed' || status === 'cancelled') {
      const message = body.error !== null && typeof body.error === 'object' ? JSON.stringify(body.error) : '视频生成失败'
      throw new Error(message)
    }
    if (status === 'completed' || status === 'succeeded') {
      const content = await getWithRetry(joinUrl(base, `videos/${encodeURIComponent(id)}/content`), headers, 300_000, request.signal)
      if (!content.ok) throw new Error(`下载 OpenAI 视频失败：HTTP ${String(content.status)}`)
      const data = await readBounded(content, request.maxBytes)
      return { done: true, value: videoResult(data, content.headers.get('content-type')?.split(';')[0] ?? 'video/mp4', joinUrl(base, `videos/${encodeURIComponent(id)}/content`)) }
    }
    const progress = typeof body.progress === 'number' ? `（${String(Math.round(body.progress * 100))}%）` : ''
    return { done: false, note: `渲染中${progress}` }
  }, { deadlineMs: 40 * 60_000, intervalMs: 5000, signal: request.signal, onProgress: request.onProgress, label: 'OpenAI 视频' })
}
